    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
        // TODO add your handling code here:
        String providerName = providerNameTf.getText().trim();
        String coverageText = coverageTf.getText().trim();
        String status = (String) statusCb.getSelectedItem();

        if (providerName.isEmpty() || coverageText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Provider Name and Coverage % are required.", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double coverage;
        try {
            coverage = Double.parseDouble(coverageText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Coverage % must be a valid number.", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            // ID is auto-generated, never typed by the user
            String networkId = UserValidationHelper.generateNextId(DataPaths.forEntity("InsuranceNetwork"), "N");
            InsuranceNetwork network = new InsuranceNetwork(networkId, providerName, coverage, status);

            loggedInAdmin.addInsuranceNetwork(network);

            loadTable();
            JOptionPane.showMessageDialog(this, providerName + " added successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
            clearFields();

        } catch (HMSException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Failed", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Validation Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_addBtnActionPerformed

    private void editBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editBtnActionPerformed
        // TODO add your handling code here:
        int row = assetsTable.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select a row to edit first.", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String networkId = networkIdTf.getText().trim();
        String providerName = providerNameTf.getText().trim();
        String coverageText = coverageTf.getText().trim();
        String status = (String) statusCb.getSelectedItem();

        double coverage;
        try {
            coverage = Double.parseDouble(coverageText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Coverage % must be a valid number.", "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            InsuranceNetwork network = new InsuranceNetwork(networkId, providerName, coverage, status);

            loggedInAdmin.updateInsuranceNetwork(network);

            loadTable();
            JOptionPane.showMessageDialog(this, providerName + " updated successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
            clearFields();

        } catch (HMSException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Failed", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Validation Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_editBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
            // TODO add your handling code here:
            int row = assetsTable.getSelectedRow();
            if (row == -1) {
                JOptionPane.showMessageDialog(this, "Must click a row", "No Selection", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String networkId = String.valueOf(model.getValueAt(row, 0));
            String providerName = String.valueOf(model.getValueAt(row, 1));

            int confirm = JOptionPane.showConfirmDialog(this,
                    "Are you sure you want to delete " + providerName + "?",
                    "Confirm Delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }

            try {
                loggedInAdmin.deleteInsuranceNetwork(networkId);

                loadTable();
                JOptionPane.showMessageDialog(this, providerName + " deleted successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
                clearFields();

            } catch (HMSException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Failed", JOptionPane.ERROR_MESSAGE);
            }
        
    }//GEN-LAST:event_deleteBtnActionPerformed
