        // Loads the table from the file, going through Admin (no direct file access here)
        private void loadTable() {
            model.setRowCount(0);
            if (loggedInAdmin == null) {
                return;
            }

            try {
                List<InsuranceNetwork> networks = loggedInAdmin.viewAllInsuranceNetworks();
                for (InsuranceNetwork n : networks) {
                    model.addRow(new String[]{
                        n.getNetworkId(),
                        n.getProviderName(),
                        String.valueOf(n.getCoveragePercent()),
                        n.getStatus()
                    });
                }
            } catch (DataFileNotFoundException e) {
                // File doesn't exist yet — table just starts empty
            }
        }

