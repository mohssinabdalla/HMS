    private void editBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editBtnActionPerformed
        // TODO add your handling code here:
       
    String fullName = fullNameTf.getText().trim();
    String email = emailTf.getText().trim();
    String phone = phoneTf.getText().trim();

    boolean success = loggedInAdmin.updateOwnProfile(fullName, email, phone);

    if (success) {
        JOptionPane.showMessageDialog(this, "Profile updated successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
        loadCurrentAdminData();
    } else {
        JOptionPane.showMessageDialog(this, "Could not update profile. Check your phone number format.", "Failed", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_editBtnActionPerformed

