    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed
        String patientId = txtPatientId.getText().trim();

        if (patientId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a Patient ID.");
            return;
        }

        PatientProfileService service = new PatientProfileService();
        String[] record = service.loadPatient(patientId);

        if (record == null) {
            JOptionPane.showMessageDialog(this, "Patient not found.");
            return;
        }

        txtFullName.setText(record[3]);
        txtEmail.setText(record[4]);
        txtPhone.setText(record[5]);
    }//GEN-LAST:event_btnLoadActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String patientId = txtPatientId.getText().trim();

        if (patientId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please load a patient first.");
            return;
        }

        String newFullName = txtFullName.getText().trim();
        String newEmail = txtEmail.getText().trim();
        String newPhone = txtPhone.getText().trim();

        if (newFullName.isEmpty() || newEmail.isEmpty() || newPhone.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }

        PatientProfileService service = new PatientProfileService();
        boolean success = service.updateProfile(patientId, newFullName, newEmail, newPhone);

        if (success) {
            JOptionPane.showMessageDialog(this, "Profile updated.");
        } else {
            JOptionPane.showMessageDialog(this, "Could not update profile (patient not found).");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
        if (currentPatient != null) {
            new controller.PatientDashboard(currentPatient).setVisible(true);
        } else {
            new controller.PatientDashboard().setVisible(true);
        }
        this.dispose();
    }//GEN-LAST:event_btnBackActionPerformed

