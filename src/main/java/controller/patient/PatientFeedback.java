    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        String patientId = txtPatientId.getText().trim();
        String ratingText = cmbRating.getSelectedItem().toString();
        String comment = txtComment.getText().trim();

        if (patientId.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Please enter Patient ID."
            );
            return;
        }

        if (comment.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Please enter your comment."
            );
            return;
        }

        int rating = Integer.parseInt(ratingText);

        PatientFeedbackService service =
            new PatientFeedbackService();

        int nextNumber = service.getFeedbackCount() + 1;

        String feedbackId =
            "FB" + String.format("%03d", nextNumber);

        Feedback feedback =
            new Feedback(
                feedbackId,
                rating,
                comment
            );
        
        
        try {
            boolean success = service.submitFeedback(feedback, patientId);

            if (success) {
                JOptionPane.showMessageDialog(
                    this,
                    "Feedback submitted successfully."
                );
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "Could not submit feedback."
                );
            }

        } catch (exceptions.InvalidRatingException e) {

            JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Invalid Rating",
                JOptionPane.WARNING_MESSAGE
            );
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
        if (currentPatient != null) {
            new controller.patient.PatientDashboard(currentPatient).setVisible(true);
        } else {
            new controller.patient.PatientDashboard().setVisible(true);
        }
        this.dispose();
    }//GEN-LAST:event_btnBackActionPerformed

