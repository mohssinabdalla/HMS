    private void searchDoctors() {

        String query = txtSearch.getText().trim();

        PatientDoctorService service = new PatientDoctorService();
        List<String[]> results = query.isEmpty()
            ? service.listAllDoctors()
            : service.searchDoctorsByName(query);

        DefaultTableModel tableModel = new DefaultTableModel(
            new Object[][] {},
            new String[] {"Doctor ID", "Name", "Email", "Phone"}
        );

        for (String[] doctor : results) {
            tableModel.addRow(new Object[] {doctor[0], doctor[3], doctor[4], doctor[5]});
        }

        tblDoctor.setModel(tableModel);
    }//GEN-LAST:event_btnSearchActionPerformed

